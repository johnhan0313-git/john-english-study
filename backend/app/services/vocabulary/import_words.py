def import_words(db: Session) -> dict[str, int]:
    existing = db.query(Word).count()
    if existing > 0:
        return {"words": existing, "groups": db.query(WordGroup).count(), "skipped": True}

    lemma_to_id: dict[str, int] = {}
    for entry in SEED_WORDS:
        word = Word(
            lemma=entry["lemma"],
            phonetic=None,
            level=entry["level"],
            pos=entry.get("pos"),
            definitions=dump_json_field(entry.get("definitions", [])),
            examples=dump_json_field(entry.get("examples", [])),
        )
        db.add(word)
        db.flush()
        lemma_to_id[entry["lemma"]] = word.id

    for group_def in WORD_GROUPS:
        group = WordGroup(
            slug=group_def["slug"],
            name_zh=group_def["name_zh"],
            name_en=group_def["name_en"],
            description=f"Theme: {group_def['name_en']}",
        )
        db.add(group)
        db.flush()
        for lemma in group_def["words"]:
            word_id = lemma_to_id.get(lemma)
            if word_id:
                db.add(WordGroupMember(group_id=group.id, word_id=word_id))
                db.add(WordTag(word_id=word_id, tag=group_def["slug"]))

    db.commit()
    return {
        "words": db.query(Word).count(),
        "groups": db.query(WordGroup).count(),
        "skipped": False,
    }


